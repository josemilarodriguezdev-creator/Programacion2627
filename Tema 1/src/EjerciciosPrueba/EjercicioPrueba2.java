package EjerciciosPrueba;//sumar los numeros del 1-10 usando un bucle for

public class EjercicioPrueba2 {
    public static void main(String[] args) {

        int suma = 0;
        for (int n1 = 1; n1 <= 10; n1++) {
            suma = suma + n1;
            System.out.println(suma);
        }

    }
}
